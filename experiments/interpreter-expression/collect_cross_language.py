"""Collect two real interpreter paths and export typed, guarded candidates.

Only the evaluation fixtures execute their source. This collector reads their
runtime bytecode and native probes. It infers a small I/O hypothesis and
retains a differential-validation grade, never a native value proof.
"""
from __future__ import annotations

import argparse
import gzip
from hashlib import sha256
import json
from pathlib import Path
import re
import shutil
import subprocess
import sys
from tempfile import TemporaryDirectory

from portable_guard_eval import classify


ROOT = Path(__file__).resolve().parent
ARTIFACTS = ROOT / "artifacts"
PY_SOURCE = ROOT / "python_branch_fixture.py"
JS_SOURCE = ROOT / "js_branch_fixture.js"
TRACER = ROOT / "trace_cross_native.py"
INPUTS = (0, 1, 9, -1, 42, 9007199254740986)
PYTHON_INPUTS = INPUTS + (9007199254740993, 1 << 70)
NATIVE_INPUTS = (0, 9)


def run(command):
    result = subprocess.run([str(item) for item in command], capture_output=True,
                            text=True, check=True, timeout=90)
    return result.stdout


def last_json(output):
    return json.loads(output.strip().splitlines()[-1])


def digest(path):
    return sha256(path.read_bytes()).hexdigest()


def make_python_bytecode(binary):
    output = ARTIFACTS / "cross_python_fixture.cpython-313.pyc"
    run([binary, "-I", "-S", "-c",
         "import py_compile,sys; py_compile.compile(sys.argv[1], cfile=sys.argv[2], "
         "invalidation_mode=py_compile.PycInvalidationMode.UNCHECKED_HASH, doraise=True)",
         PY_SOURCE, output])
    return output


def native_capture(engine, binary, program, value, label, bytecode_filter=None):
    with TemporaryDirectory(prefix="r4_cross_") as directory:
        temp = Path(directory)
        marker, raw = temp / "marker.json", temp / "native.json"
        command = [sys.executable, TRACER, engine, binary, marker, raw]
        if engine == "python":
            command += ["-I", "-S", program, "--mark", marker, "--native-sync", value]
        else:
            command += ["--jitless", "--no-warnings", "--print-bytecode",
                        f"--print-bytecode-filter={bytecode_filter}", program,
                        "--mark", marker, "--native-sync", value]
        run(command)
        report = json.loads(raw.read_text())
        stdout = raw.with_suffix(".stdout.txt").read_text()
        packed = gzip.compress(raw.read_bytes(), mtime=0)
        archive = ARTIFACTS / f"cross_{label}_native.json.gz"
        archive.write_bytes(packed)
        artifact = {"raw_trace": str(archive.relative_to(ROOT)),
                    "raw_trace_sha256": sha256(packed).hexdigest(),
                    "native_hits_all_code": report["hit_count"],
                    "breakpoint_count": report["breakpoint_count"]}
        if engine == "javascript":
            bytecode_output = ARTIFACTS / f"cross_{label}_bytecode.txt"
            bytecode_output.write_text(stdout)
            artifact["bytecode_output"] = str(bytecode_output.relative_to(ROOT))
        return report, stdout, artifact


def python_opcode_trace(binary, program, value):
    with TemporaryDirectory(prefix="r4_python_opcode_") as directory:
        temp = Path(directory)
        trace, marker = temp / "opcode.json", temp / "marker.json"
        output = run([binary, "-I", "-S", program, value,
                      "--trace", trace, "--mark", marker])
        path = ARTIFACTS / f"cross_python_{value}_opcodes.json"
        path.write_bytes(trace.read_bytes())
        return json.loads(trace.read_text()), json.loads(marker.read_text()), \
            last_json(output), str(path.relative_to(ROOT))


def parse_v8_bytecode(output, function):
    header = re.search(r"\[generated bytecode for function: " + re.escape(function) +
                       r" \([^\n]+\)\]", output)
    length = re.search(r"Bytecode length: (\d+)", output)
    if not header or not length:
        raise ValueError(f"V8 did not print {function} bytecode")
    instructions = []
    pattern = re.compile(r"0x([0-9a-f]+)\s+@\s+(\d+)\s+:\s+((?:[0-9a-f]{2}\s+)+?)"
                         r"([A-Za-z][A-Za-z0-9_]*)")
    for match in pattern.finditer(output):
        instructions.append({"address": int(match.group(1), 16),
                             "offset": int(match.group(2)),
                             "bytes": match.group(3).strip().split(),
                             "opname": match.group(4)})
    if not instructions or instructions[0]["offset"] != 0 or \
            any(item["address"] != instructions[0]["address"] + item["offset"]
                for item in instructions):
        raise ValueError("V8 bytecode address/offset mapping changed")
    canonical = [{"offset": item["offset"], "bytes": item["bytes"],
                  "opname": item["opname"]} for item in instructions]
    return {"length": int(length.group(1)), "base": instructions[0]["address"],
            "instructions": canonical,
            "sha256": sha256(json.dumps(canonical, sort_keys=True).encode()).hexdigest()}


def python_native_projection(native, marker, opcode_trace):
    if native["marker"]["bytecode_sha256"] != marker["bytecode_sha256"]:
        raise ValueError("CPython native and opcode trace code objects differ")
    groups = {}
    for row in native["events"]:
        if row["code_name"]:
            groups.setdefault(row["code_name"], []).append(row)
    result = {}
    for name in ("branchCall", "addFive"):
        rows = groups[name]
        base = min(int(row["byte_address"], 16) for row in rows)
        instructions = {row["offset"]: row for row in opcode_trace["instructions"][name]}
        sequence = []
        for row in rows:
            offset = int(row["byte_address"], 16) - base
            if offset not in instructions or instructions[offset]["opcode_byte"] != row["fetched_byte"] or \
                    row["fetched_byte"] != row["opcode_register"]:
                raise ValueError("CPython native dispatch does not match frozen code byte")
            sequence.append({"offset": offset, "opcode_byte": row["fetched_byte"],
                             "opname": instructions[offset]["opname"],
                             "native_dispatch_pc": row["native_pc"],
                             "native_handler_pc": row["handler_address"]})
        runtime = [row["offset"] for row in opcode_trace["events"]
                   if row["event"] == "opcode" and row["function"] == name]
        result[name] = {"native_dispatch_sequence": sequence,
                        "runtime_opcode_offsets": runtime,
                        "runtime_offsets_without_native_dispatch_hit": sorted(set(runtime) -
                                                                               {row["offset"] for row in sequence})}
    return result


def js_native_projection(native, bytecode):
    base, end = bytecode["base"], bytecode["base"] + bytecode["length"]
    instructions = {item["offset"]: item for item in bytecode["instructions"]}
    rows = [row for row in native["events"] if base <= int(row["byte_address"], 16) < end]
    sequence = []
    for row in rows:
        offset = int(row["byte_address"], 16) - base
        if row["kind"] != "handler_entry":
            continue
        if offset not in instructions or int(instructions[offset]["bytes"][0], 16) != row["fetched_byte"] or \
                not row["dispatch_table_match"]:
            raise ValueError("Ignition native handler/bytecode/table mapping differs")
        sequence.append({"offset": offset, "opcode_byte": row["fetched_byte"],
                         "opname": instructions[offset]["opname"],
                         "native_handler_pc": row["native_pc"]})
    if not sequence or sequence[0]["offset"] != 0 or \
            not any(row["kind"] == "entry_dispatch" for row in rows):
        raise ValueError("missing Ignition entry dispatch for target function")
    return {"native_handler_entry_sequence": sequence,
            "native_entry_dispatch_count": sum(row["kind"] == "entry_dispatch" for row in rows),
            "static_offsets_without_handler_entry": sorted(set(instructions) -
                                                           {row["offset"] for row in sequence})}


def fixture_output(engine, binary, program, value, mode="integer"):
    if engine == "python":
        return last_json(run([binary, "-I", "-S", program, "--mode", mode, value]))
    return last_json(run([binary, "--jitless", "--no-warnings", program,
                          "--mode", "object" if mode == "object" else "number", value]))


def output_number(engine, output):
    return int(output["result"]) if engine == "python" else int(float(output["result"]))


def infer_piecewise(training):
    candidates = []
    for pivot in training:
        others = {x: y for x, y in training.items() if x != pivot}
        if len(others) >= 2 and len({y - x for x, y in others.items()}) == 1:
            candidates.append((pivot, training[pivot], next(iter({y - x for x, y in others.items()}))))
    if len(candidates) != 1:
        raise ValueError(f"small piecewise hypothesis is ambiguous: {candidates}")
    return candidates[0]


def make_summary(engine, binary, program, sort, observations, provenance,
                 bytecode_identity, native_paths):
    training = {x: observations[x] for x in (0, 1, 9)}
    pivot, special, delta = infer_piecewise(training)
    constant = lambda n: {"const": str(n), "sort": sort}
    summary = {"schema_version": "portable-guarded-expression-v1",
               "semantic_model": {"value_sort": sort, "arithmetic":
                                  "unbounded integer" if sort == "Z" else "IEEE-754 binary64 Number",
                                  "memory": "ordered byte memory; opaque object effects remain unknown"},
               "identity": {"binary_sha256": digest(binary), "program_sha256": digest(program),
                            "bytecode_sha256": bytecode_identity,
                            "code_epoch": "CPython 3.13 cold code" if engine == "python" else
                                          "Node 24.19.0 --jitless Ignition"},
               "interface": {"input": {"name": "X", "sort": sort,
                                       "binding": "decimal CLI text converted by runtime"},
                             "output": {"name": "result", "sort": sort,
                                        "binding": "fixture JSON output"}},
               "cases": [
                   {"guard": {"op": "eq", "left": "X", "right": constant(pivot)},
                    "result": constant(special),
                    "validation_level": "differentially_validated"},
                   {"guard": {"op": "ne", "left": "X", "right": constant(pivot)},
                    "result": {"op": "add", "sort": sort, "args": ["X", constant(delta)]},
                    "validation_level": "differentially_validated"}],
               "admitted_input_witnesses": [str(x) for x in observations],
               "input_integer_bounds": None if engine == "python" else
                                       [-9007199254740986, 9007199254740986],
               "preconditions": ["fixed executable and program/bytecode identity",
                                 "only listed integer witnesses have been admitted",
                                 "runtime object and exceptional effects outside candidate"],
               "uncovered": ["other input values and VM states", "objects and implicit coercion",
                             "exceptions", "full native value/dataflow", "path completeness"],
               "termination_claim": "partial", "evidence": provenance,
               "native_paths": native_paths}
    if engine == "javascript":
        summary["uncovered"].append("JIT/deopt and non-safe Number values")
    checks = []
    for x in observations:
        decision = classify(summary, digest(binary), digest(program), x)
        if decision["status"] != "differentially_validated" or \
                decision["predicted_output"] != observations[x]:
            raise ValueError(f"{engine} candidate disagrees with held-out input {x}")
        checks.append({"input": str(x), "observed": observations[x],
                       "predicted": decision["predicted_output"]})
    summary["verification"] = {"training_inputs": [0, 1, 9], "checks": checks,
                               "new_input_query": classify(summary, digest(binary), digest(program), 2),
                               "code_mismatch_query": classify(summary, "0" * 64, digest(program), 9)}
    if summary["verification"]["new_input_query"]["status"] != "unknown" or \
            summary["verification"]["code_mismatch_query"]["status"] != "unknown":
        raise ValueError("fail-closed classification was lost")
    return summary


def main():
    parser = argparse.ArgumentParser()
    parser.add_argument("--python", type=Path, default=Path("/usr/bin/python3.13"))
    parser.add_argument("--node", type=Path, default=Path(shutil.which("node") or ""))
    args = parser.parse_args()
    ARTIFACTS.mkdir(exist_ok=True)
    py, node = args.python.resolve(), args.node.resolve()
    py_program = make_python_bytecode(py)
    pcode = json.loads((ROOT / "cross_dispatch_pcode.json").read_text())
    if {item["engine"]: item["binary_sha256"] for item in pcode["slices"]
        if item["engine"] in ("python", "javascript")} != \
            {"python": digest(py), "javascript": digest(node)}:
        raise ValueError("dispatch P-code does not match tested executables")
    native, runtime, provenance = {}, {}, {}
    for value in NATIVE_INPUTS:
        p_native, _, p_art = native_capture("python", py, py_program, value,
                                            f"python_{value}")
        p_trace, p_marker, p_output, p_trace_path = python_opcode_trace(py, py_program, value)
        p_projection = python_native_projection(p_native, p_marker, p_trace)
        if int(p_output["result"]) != (10 if value == 0 else value + 5):
            raise ValueError("CPython fixture changed")
        native[f"python_{value}"] = p_projection
        provenance[f"python_{value}"] = {**p_art, "opcode_trace": p_trace_path}
        j_native, j_stdout, j_art = native_capture("javascript", node, JS_SOURCE, value,
                                                  f"js_branch_{value}", "branchCall")
        j_bytecode = parse_v8_bytecode(j_stdout, "branchCall")
        native[f"js_branch_{value}"] = js_native_projection(j_native, j_bytecode)
        provenance[f"js_branch_{value}"] = j_art
        runtime[f"python_{value}"] = p_marker
        runtime[f"js_branch_{value}"] = j_bytecode
    if runtime["js_branch_0"]["sha256"] != runtime["js_branch_9"]["sha256"]:
        raise ValueError("Ignition bytecode differed between two branch witnesses")
    j_native, j_stdout, j_art = native_capture("javascript", node, JS_SOURCE, 9,
                                              "js_add_9", "addFive")
    add_bytecode = parse_v8_bytecode(j_stdout, "addFive")
    native["js_add_9"] = js_native_projection(j_native, add_bytecode)
    provenance["js_add_9"] = j_art
    observations = {}
    for engine, binary, program in (("python", py, py_program),
                                    ("javascript", node, JS_SOURCE)):
        values = PYTHON_INPUTS if engine == "python" else INPUTS
        observations[engine] = {x: output_number(engine, fixture_output(engine, binary, program, x))
                                for x in values}
    python_summary = make_summary("python", py, py_program, "Z", observations["python"],
                                  {key: value for key, value in provenance.items()
                                   if key.startswith("python")},
                                  runtime["python_9"]["bytecode_sha256"],
                                  {key: value for key, value in native.items()
                                   if key.startswith("python")})
    js_summary = make_summary("javascript", node, JS_SOURCE, "F64", observations["javascript"],
                              {key: value for key, value in provenance.items()
                               if key.startswith("js")},
                              {"branchCall": runtime["js_branch_9"]["sha256"],
                               "addFive": add_bytecode["sha256"]},
                              {key: value for key, value in native.items()
                               if key.startswith("js")})
    for name, summary in (("python", python_summary), ("javascript", js_summary)):
        (ROOT / f"{name}_portable_case.json").write_text(json.dumps(summary, indent=2) + "\n")
    effects = {engine: fixture_output(engine, binary, program, "ignored", mode="object")
               for engine, binary, program in (("python", py, py_program),
                                               ("javascript", node, JS_SOURCE))}
    out_of_domain = {engine: fixture_output(engine, binary, program, 9007199254740993)
                     for engine, binary, program in (("python", py, py_program),
                                                     ("javascript", node, JS_SOURCE))}
    object_unknown = {
        "python": classify(python_summary, digest(py), digest(py_program), object()),
        "javascript": classify(js_summary, digest(node), digest(JS_SOURCE), object())}
    precision_unknown = {
        "python": classify(python_summary, digest(py), digest(py_program), 9007199254740993),
        "javascript": classify(js_summary, digest(node), digest(JS_SOURCE), 9007199254740993)}
    if any(item["status"] != "unknown" for item in object_unknown.values()) or \
            precision_unknown["python"]["status"] != "differentially_validated" or \
            precision_unknown["javascript"]["status"] != "unknown":
        raise ValueError("unsupported object or precision path was admitted")
    lua = json.loads((ROOT / "lua_pre_python_js_port.json").read_text())
    lua_shared_eval = classify(lua, digest(ROOT / "lua_interpreter_fixture"),
                               digest(ROOT / "lua_branch_call.luac"), 9)
    if lua_shared_eval["predicted_output"] != 14:
        raise ValueError("shared evaluator failed the saved Lua case")
    report = {"schema_version": 1, "languages": ["Lua", "Python", "JavaScript"],
              "common_evaluator_reused_for_lua": lua_shared_eval,
              "pcode_dispatch": "cross_dispatch_pcode.json",
              "candidate_validation_counts": {"python": len(PYTHON_INPUTS),
                                              "javascript": len(INPUTS)},
              "native_branch_witnesses": list(NATIVE_INPUTS),
              "native_add_call_witness": 9,
              "object_effects_unknown": effects,
              "object_queries": object_unknown,
              "number_precision_outside_admitted_domain": out_of_domain,
              "precision_queries": precision_unknown,
              "claims": {"bytecode_to_native_dispatch": "observed on two branch paths per engine",
                         "input_to_output_expression": "I/O hypothesis; differential validation only",
                         "all_paths_or_native_value_proof": False}}
    (ROOT / "cross_language_result.json").write_text(json.dumps(report, indent=2) + "\n")
    print(json.dumps({"native_paths": 5,
                      "differential_cases": len(PYTHON_INPUTS) + len(INPUTS),
                      "lua_shared_evaluator": lua_shared_eval["predicted_output"],
                      "object_effects": effects,
                      "precision_difference": out_of_domain}))


if __name__ == "__main__":
    main()
